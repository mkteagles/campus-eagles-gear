export const lessons = course.modules.flatMap((module) =>
  module.lessons.map((lesson) => ({ ...lesson, moduleId: module.id, moduleTitle: module.title })),
)

export const getLesson = (lessonId) => lessons.find((lesson) => lesson.id === lessonId)
export const getFirstLessonId = () => lessons[0].id
export const getLessonNeighbors = (lessonId) => {
  const index = lessons.findIndex((lesson) => lesson.id === lessonId)
  return { previous: lessons[index - 1] || null, next: lessons[index + 1] || null }
}
