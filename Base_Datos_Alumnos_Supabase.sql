-- Función segura para comprobar el rol sin provocar recursión en las políticas.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.student_profiles
    where id = auth.uid()
      and role = 'admin'
      and status = 'active'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.is_active_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.student_profiles
    where id = auth.uid()
      and status = 'active'
  );
$$;

revoke all on function public.is_active_user() from public;
grant execute on function public.is_active_user() to authenticated;

-- El alumno confirma el cambio de su contraseña desde una sesión autenticada.
-- La contraseña nunca se guarda en esta tabla; solamente se registra que completó el paso.
create or replace function public.mark_password_changed()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.student_profiles
  set must_change_password = false,
      updated_at = now()
  where id = auth.uid();
end;
$$;

revoke all on function public.mark_password_changed() from public;
revoke all on function public.mark_password_changed() from anon;
grant execute on function public.mark_password_changed() to authenticated;

-- Perfiles: cada alumno ve y actualiza solamente su perfil.
drop policy if exists "Students can view their own profile" on public.student_profiles;
create policy "Students can view their own profile"
on public.student_profiles for select
to authenticated
using (auth.uid() = id or public.is_admin());

drop policy if exists "Students can update their own profile" on public.student_profiles;
create policy "Students can update their own profile"
on public.student_profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

-- Cursos: los usuarios registrados pueden consultar cursos activos.
drop policy if exists "Authenticated users can view active courses" on public.courses;
create policy "Authenticated users can view active courses"
on public.courses for select
to authenticated
using (active = true and public.is_active_user());

-- Inscripciones: cada alumno ve solamente las suyas.
drop policy if exists "Students can view their own enrollments" on public.course_enrollments;
create policy "Students can view their own enrollments"
on public.course_enrollments for select
to authenticated
using ((auth.uid() = user_id and public.is_active_user()) or public.is_admin());

-- Progreso: solamente el alumno dueño del registro puede verlo o modificarlo,
-- y únicamente mientras tenga una inscripción activa o completada.
drop policy if exists "Students can view their own progress" on public.lesson_progress;
create policy "Students can view their own progress"
on public.lesson_progress for select
to authenticated
using ((auth.uid() = user_id and public.is_active_user()) or public.is_admin());

drop policy if exists "Students can create their own progress" on public.lesson_progress;
create policy "Students can create their own progress"
on public.lesson_progress for insert
to authenticated
with check (
  auth.uid() = user_id
  and public.is_active_user()
  and exists (
    select 1
    from public.course_enrollments enrollment
    where enrollment.user_id = auth.uid()
      and enrollment.course_id = lesson_progress.course_id
      and enrollment.status in ('active', 'completed')
      and (enrollment.expires_at is null or enrollment.expires_at > now())
  )
);

drop policy if exists "Students can update their own progress" on public.lesson_progress;
create policy "Students can update their own progress"
on public.lesson_progress for update
to authenticated
using (auth.uid() = user_id)
with check (
  auth.uid() = user_id
  and public.is_active_user()
  and exists (
    select 1
    from public.course_enrollments enrollment
    where enrollment.user_id = auth.uid()
      and enrollment.course_id = lesson_progress.course_id
      and enrollment.status in ('active', 'completed')
      and (enrollment.expires_at is null or enrollment.expires_at > now())
  )
);

