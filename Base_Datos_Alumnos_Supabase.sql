-- 1. PERFIL DE CADA ALUMNO
create table if not exists public.student_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  phone text,
  company_name text,
  crm_customer_id bigint,
  city text,
  state text,
  country text default 'México',
  role text not null default 'student'
    check (role in ('admin', 'student')),
  status text not null default 'active'
    check (status in ('active', 'inactive', 'blocked')),
  must_change_password boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Compatibilidad por si se ejecuta sobre una versión anterior del esquema.
alter table public.student_profiles
  add column if not exists role text not null default 'student';

alter table public.student_profiles
  add column if not exists must_change_password boolean not null default true;

alter table public.student_profiles
  add column if not exists crm_customer_id bigint;

create unique index if not exists student_profiles_crm_customer_unique
  on public.student_profiles (crm_customer_id)
  where crm_customer_id is not null;

-- 2. CATÁLOGO DE CURSOS
create table if not exists public.courses (
  id text primary key,
  title text not null,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Curso inicial utilizado por la plataforma.
insert into public.courses (id, title, description, active)
values (
  'seminario-empresarial',
  'Seminario Empresarial',
  'De técnico a dueño: construye una empresa ordenada, rentable y con dirección.',
  true
)
on conflict (id) do update set
  title = excluded.title,
  description = excluded.description,
  active = excluded.active,
  updated_at = now();

-- 3. INSCRIPCIONES
create table if not exists public.course_enrollments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id text not null references public.courses(id) on delete cascade,
  status text not null default 'active'
    check (status in ('active', 'completed', 'expired', 'cancelled')),
  enrolled_at timestamptz not null default now(),
  expires_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (user_id, course_id)
);

-- 4. PROGRESO DE LAS LECCIONES
create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id text not null references public.courses(id) on delete cascade,
  lesson_id text not null,
  completed boolean not null default false,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  unique (user_id, course_id, lesson_id)
);

-- 5. ÍNDICES PARA CONSULTAS RÁPIDAS
create index if not exists student_profiles_status_idx
  on public.student_profiles (status);

create index if not exists student_profiles_role_idx
  on public.student_profiles (role);

create index if not exists course_enrollments_user_idx
  on public.course_enrollments (user_id);

create index if not exists course_enrollments_course_status_idx
  on public.course_enrollments (course_id, status);

create index if not exists lesson_progress_user_course_idx
  on public.lesson_progress (user_id, course_id);

-- 6. ACTUALIZACIÓN AUTOMÁTICA DE updated_at
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_student_profiles_updated_at on public.student_profiles;
create trigger set_student_profiles_updated_at
before update on public.student_profiles
for each row execute function public.set_updated_at();

drop trigger if exists set_courses_updated_at on public.courses;
create trigger set_courses_updated_at
before update on public.courses
for each row execute function public.set_updated_at();

drop trigger if exists set_course_enrollments_updated_at on public.course_enrollments;
create trigger set_course_enrollments_updated_at
before update on public.course_enrollments
for each row execute function public.set_updated_at();

drop trigger if exists set_lesson_progress_updated_at on public.lesson_progress;
create trigger set_lesson_progress_updated_at
before update on public.lesson_progress
for each row execute function public.set_updated_at();

-- 7. AL CREAR UN USUARIO:
--    - crea su perfil;
--    - la inscripción se asigna explícitamente desde el panel o una integración.
create or replace function public.handle_new_student()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.student_profiles (
    id,
    email,
    full_name,
    phone,
    company_name
  )
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    coalesce(new.raw_user_meta_data ->> 'company_name', '')
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_create_student on auth.users;
create trigger on_auth_user_created_create_student
after insert on auth.users
for each row execute function public.handle_new_student();

-- Si ya existían usuarios antes de correr este script, también los agrega.
insert into public.student_profiles (id, email, full_name)
select
  id,
  email,
  coalesce(raw_user_meta_data ->> 'full_name', '')
from auth.users
on conflict (id) do nothing;

